import { getSetting, setSetting } from '../db/repo.js';

export const STYLE_GUIDE_KEY = 'style_guide';

export const DEFAULT_STYLE_GUIDE = `## Формат и оформление поста

Ты готовишь пост для канала в Telegram и Max. Отвечай строго в заданной JSON-схеме, без текста вне JSON.

### Исследование
- Сегодня {{date}}. Обязательно используй веб-поиск: найди 2–4 свежих и надёжных источника по теме и опирайся только на факты из них. Не выдумывай цифры, даты и цитаты.
- В поле sources перечисли реально использованные источники с точными URL и короткими названиями (название издания или документа).

### Текст (поле body)
- Язык: {{language}}. Объём: до {{max_body_length}} символов.
- Структура: 1 короткий абзац-хук (почему это важно читателю), затем 2–4 абзаца сути с конкретикой и цифрами, в конце 1 абзац с выводом или практическим советом. Абзацы разделяй пустой строкой.
- Разрешённая разметка: **жирный** для ключевых мыслей и цифр, _курсив_ для акцентов, [текст](url) для ссылок, строки с "- " для списков, строки с "> " для цитат. Никаких заголовков (#), HTML, таблиц и markdown-картинок.
- 1–3 уместных эмодзи в начале абзацев или пунктов списка, не больше. Без эмодзи внутри предложений.
- Короткие предложения, без воды, канцелярита и кликбейта. Не повторяй темы из списка уже опубликованных постов.
- Не вставляй в текст ссылки на источники, названия сайтов в скобках и сноски вроде «(nalog.gov.ru)» или [1]: блок источников добавляется автоматически из поля sources. Ссылка внутри текста уместна только если она сама по себе полезна читателю (например, на сервис или документ).

### Остальные поля
- title: до 80 символов, цепляющий, без точки в конце и без эмодзи.
- image_strategy: "source", если пост про конкретное событие или новость (сделка, отчёт, заявление, запуск продукта, происшествие) и среди источников есть статья, у которой наверняка есть собственное фото события. "stock", если тема общая: советы, объяснения, обзоры, подборки.
- image_source_url: при image_strategy = "source" точный URL той статьи из sources, с которой брать фото (предпочитай первоисточник: сайт компании, ведомства, крупного издания). Иначе null.
- image_query: заполняй всегда, это запасной вариант: 2–5 английских слов, описывающих конкретную визуальную сцену для стокового фото (например "stock market trading screen" или "family planning budget at kitchen table"). Без текста, логотипов и имён людей.
- image_alt: одно предложение, что должно быть на картинке.
- hashtags: 2–4 штуки на языке поста в формате #слово, без пробелов.`;

export function getStyleGuide(): string {
  return getSetting(STYLE_GUIDE_KEY) ?? DEFAULT_STYLE_GUIDE;
}

export function saveStyleGuide(text: string): void {
  setSetting(STYLE_GUIDE_KEY, text);
}

export function renderStyleGuide(vars: { date: string; language: string; maxBodyLength: number }): string {
  return getStyleGuide()
    .replaceAll('{{date}}', vars.date)
    .replaceAll('{{language}}', vars.language)
    .replaceAll('{{max_body_length}}', String(vars.maxBodyLength));
}
